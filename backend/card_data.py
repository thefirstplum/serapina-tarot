def get_card(card_id):
    """정/역방향 id 를 받아 (데이터, 역방향여부) 반환"""
    reversed_ = card_id.endswith("_r")
    base_id = card_id[:-2] if reversed_ else card_id
    return CARD_DB.get(base_id), reversed_


def detect_question_scope(question="", spread_type=""):
    """질문이 묻는 시간 범위를 판정한다.

    반환: 'day' | 'week' | 'month' | 'year' | 'when' | None
    스프레드 종류가 명시돼 있으면 그걸 우선한다(가장 확실한 신호).
    """
    st = (spread_type or "").strip()
    if st in _SCOPE_BY_SPREAD:
        return _SCOPE_BY_SPREAD[st]

    q = question or ""
    # "언제" 류는 시기 자체가 답이라 따로 취급
    if re.search(r"언제|며칠|얼마나 (걸려|남|기다)|몇 ?(일|주|달|개월)", q):
        return "when"
    if re.search(r"오늘|지금|이따|오늘밤|내일", q):
        return "day"
    if re.search(r"이번\s*주|주간|이번주|다음\s*주", q):
        return "week"
    if re.search(r"이번\s*달|월간|다음\s*달|이달", q):
        return "month"
    if re.search(r"올해|내년|연간|년말|연말|한 ?해", q):
        return "year"
    return None


