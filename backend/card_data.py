def _timing_line(card, scope):
    """질문 범위에 맞춘 시기 문구. scope 가 없으면 카드 원래 시기감."""
    if scope in _TIMING_BY_SCOPE:
        return _TIMING_BY_SCOPE[scope].get(card["timing_scale"], card["timing"])
    return card["timing"]


def build_card_context(card_id, topic=None, position=None, scope=None,
                       with_timing=True):
    """카드 한 장을 프롬프트에 넣을 블록으로 만든다.

    topic: 'love' | 'career' | 'money' | 'self' | 'daily' | None
    position: 스프레드 위치 라벨 (예: '그 사람의 진심')
    scope: detect_question_scope() 결과. 시기 표현을 질문 범위에 맞춰 환산
    """
    card, is_rev = get_card(card_id)
    if not card:
        return f"[{position or '카드'}] 알 수 없는 카드 ({card_id})"

    head = card["name"] + (" (역방향)" if is_rev else "")
    if position:
        head = f"[{position}] {head}"

    lines = [head]
    lines.append(f"  그림: {card['image']}")

    if is_rev:
        lines.append(f"  의미: {card['reversed']}")
        lines.append(f"  키워드: {', '.join(card['rev_keys'])}")
        lines.append("  ※ 역방향 — 아래 해석들이 막히거나·지연되거나·안으로만 향하는 형태로 나타남")
    else:
        lines.append(f"  의미: {card['upright']}")
        lines.append(f"  키워드: {', '.join(card['up_keys'])}")

    domain = _DOMAIN_BY_TOPIC.get(topic or "", None)
    if domain:
        label = {"love": "이 질문(연애)에서", "career": "이 질문(직업·진로)에서",
                 "money": "이 질문(금전)에서"}[domain]
        lines.append(f"  {label}: {card[domain]}")
    else:
        # 주제가 불분명할 때 세 영역을 그냥 나열하면 모델이 연애를 골라서,
        # "이제 나 좀 괜찮아진 거 같아 보여?" 같은 질문에도 연애 얘기가 나갔다.
        lines.append("  ※ 질문 주제가 특정되지 않았다. 아래는 영역별 참고일 뿐이다."
                     " 사용자가 실제로 물은 영역만 골라 쓰고,"
                     " 질문에 없는 영역(특히 연애)을 임의로 끌어오지 마라.")
        lines.append(f"  (연애) {card['love']}")
        lines.append(f"  (직업) {card['career']}")
        lines.append(f"  (금전) {card['money']}")

    lines.append(f"  조언 방향: {card['advice']}")
    if with_timing:
        lines.append(f"  시기감: {_timing_line(card, scope)}")

    yn = card["yesno"]
    if is_rev and yn == "yes":
        yn = "maybe"
    elif is_rev and yn == "maybe":
        yn = "no"
    lines.append(f"  yes/no 무게: {_YESNO_LABEL[yn]}")
    return "\n".join(lines)


