def find_cards_in_text(text: str):
    """질문에 등장한 카드 이름을 (표시이름, 역방향여부) 목록으로 돌려준다."""
    if not text:
        return []
    rev = bool(re.search(r'(역방향|역위치|뒤집)', text))
    # 커뮤니티에서는 슈트를 영어 음차로 더 자주 쓴다(완드/소드/컵스).
    # 내부 명칭(지팡이/검/컵)으로 바꿔 놓고 찾는다.
    norm = text
    for alias, real in (('완드', '지팡이'), ('완즈', '지팡이'), ('원드', '지팡이'),
                        ('소드', '검'), ('스워드', '검'), ('컵스', '컵'),
                        ('펜타클스', '펜타클'), ('코인', '펜타클')):
        norm = norm.replace(alias, real)
    text = norm
    found, seen = [], set()
    for cid, card in CARD_DB.items():
        for nm in (card.get("name"), card.get("full_name")):
            if nm and len(nm) >= 2 and nm in text and nm not in seen:
                seen.add(nm)
                found.append((nm, rev))
                break
    return found


def build_spread_context(card_ids, topic=None, positions=None,
                         question="", spread_type=""):
    """뽑힌 카드 전체를 프롬프트 블록으로. 시기 환산과 yes/no 종합 포함"""
    positions = positions or []
    scope = detect_question_scope(question, spread_type)

    # 진단명이나 치료가 걸린 질문에는 시기 데이터를 아예 넣지 않는다.
    # 시기를 단정하지 말라고 지시해도 카드별 시기감을 주면 모델은 그걸 쓴다.
    # 지시를 넣은 뒤에도 "2~3개월 뒤쯤이면 벗어나"가 계속 나왔다(2026-09-15).
    _clinical = bool(question and _CLINICAL.search(question))
    # 타로 자체를 묻는 질문에 시기감을 주면 "한 달 안에 신호가 온다" 같은 예언으로 빠진다
    try:
        from question_intent import detect_intent as _di
        _meta = bool(question) and _di(question).get('intent') == 'meta'
    except Exception:
        _meta = False

    blocks = []
    score = 0
    for i, cid in enumerate(card_ids):
        pos = positions[i] if i < len(positions) else None
        blocks.append(build_card_context(cid, topic, pos, scope,
                                         with_timing=not (_clinical or _meta)))
        card, is_rev = get_card(cid)
        if card:
            v = {"yes": 1, "maybe": 0, "no": -1}[card["yesno"]]
            score += -v if is_rev else v

    if score >= 2:
        verdict = "전체적으로 긍정 쪽으로 확실히 기울어 있음"
    elif score == 1:
        verdict = "긍정 쪽이 조금 더 우세함"
    elif score == 0:
        verdict = "팽팽함 — 조건에 따라 갈림"
    elif score == -1:
        verdict = "부정 쪽이 조금 더 우세함"
    else:
        verdict = "전체적으로 부정 쪽으로 확실히 기울어 있음"

    out = "\n\n".join(blocks)
    out += f"\n\n[카드 종합 판정] {verdict} (점수 {score:+d})"

    # 시기 사용 규칙. 없으면 카드마다 시기를 반복한다
    if _clinical or _meta:
        pass  # 임상·메타 질문: 시기 관련 지시를 아예 주지 않는다
    elif scope == "when":
        out += ("\n[시기 지시] 사용자가 '언제'를 물었다. 시기를 리딩 앞부분에 "
                "한 번, 분명하게 제시할 것. 카드마다 반복하지 말 것.")
    elif scope:
        label = {"day": "하루", "week": "이번 주", "month": "이번 달", "year": "올해"}[scope]
        out += (f"\n[시기 지시] 질문 범위는 '{label}'이다. 위 시기감은 그 안에서의 "
                f"앞뒤 순서를 뜻한다. 범위 밖 시기(예: 몇 개월 뒤)를 말하지 말 것. "
                f"시기 표현은 리딩 전체에서 최대 2회.")
    else:
        out += ("\n[시기 지시] 시기 표현은 리딩 전체에서 한 번만. "
                "카드마다 반복하면 문장이 지저분해진다.")
    if not (_clinical or _meta):
        out += ("\n[시기 표기] 위 '시기감'은 참고용 메모다. 문구를 그대로 옮기지 말고 "
                "네 문장으로 자연스럽게 녹여라. 같은 뜻의 시간 표현을 한 문장 안에 "
                "두 번 겹쳐 쓰지 마라.")
    # 카드마다 시기감이 다르다(컵=개월, 지팡이=일·주). 그대로 나열하면 "6개월 뒤부터 회복"
    # 다음에 "그 흐름을 타고 2주 뒤부터"가 붙는 식으로 시간선이 엉켰다(2026-09-15).
    if not (_clinical or _meta):
        out += ("\n[시기 일관성] 시기를 두 번 이상 말할 거면 반드시 이른 것부터 "
                "늦은 순서로 배치해라. 늦은 시점을 먼저 말해놓고 더 이른 시점을 "
                "'그 뒤에·그 흐름을 타고'로 이어 붙이면 읽는 사람이 순서를 알 수 없다. "
                "카드별 시기감을 그대로 나열하지 말고, 이 질문의 답이 되는 "
                "하나의 시간선으로 합쳐서 정리해라.")

    # 카드별 단락은 "1~2주 안에 연락 온다", 종합은 "연락 올 가능성 낮아"로 어긋난 적이 있다
    out += ("\n[결론 일관성] 카드별 단락에서 한 말과 마지막 종합이 서로 어긋나면 안 된다. "
            "개별 카드가 긍정 신호를 줘도 종합 판정이 부정이면, 그 신호를 "
            "'그래도 결론을 뒤집지는 못한다'는 맥락으로 정리해라. "
            "반대도 마찬가지다. 읽는 사람이 '되는 거야 안 되는 거야'라고 "
            "되묻게 만들지 마라.")

    # 카드 데이터 문구를 그대로 옮기면 같은 카드를 뽑은 사람마다 같은 문장을 받는다.
    # 검8 조언이 리딩 12건 중 3건에 그대로 나왔다(2026-09-11).
    out += ("\n[표현 규칙] 위 '의미·조언 방향'은 참고 메모지 그대로 옮겨 쓸 문장이 아니다. "
            "특히 조언 문구를 복사하면 같은 카드를 뽑은 사용자마다 똑같은 리딩을 받게 된다. "
            "반드시 이 사람의 질문·상황에 맞춰 네 문장으로 다시 써라.")

    named = find_cards_in_text(question) if question else []
    if named:
        _txt = ", ".join(f"{n}{'(역방향)' if r else ''}" for n, r in named[:3])
        out += (f"\n[사용자가 지목한 카드] 질문에 '{_txt}' 가(이) 나온다."
                " 사용자는 바로 이 카드의 뜻을 물었다."
                " 우리가 새로 뽑은 카드만 풀고 이 카드를 빼먹으면 답을 안 한 것이다."
                " 이 카드부터 먼저, 분명하게 설명해라.")

    # 병을 카드로 판정하면 해가 된다. 불안장애 질문에 "3~4주 안에 통제할 수 있다는
    # 확신이 온다"며 불안을 성장통으로 축소하고, 전문가 얘기는 한 줄도 없던 답이 나왔다(2026-09-15).
    # 위기 감지기는 자해·자살 표현만 잡기 때문에 여기서 따로 막는다.
    if _clinical:
        out += ("\n[의료 주제 — 반드시 지킬 것] 이 질문에는 병·진단·치료가 걸려 있다."
                " 낫는지 안 낫는지를 카드로 판정하지 마라."
                " 회복·치료 시기를 숫자로 말하지 마라. '한 달 안에', '2~3개월 뒤쯤이면'"
                " 같은 표현을 쓰면 안 된다. (그래서 위 카드 정보에 시기감을 빼 뒀다)"
                " 좋아진다고 단정하지도 마라. '반드시 이루어져', '결국 벗어나게 돼'"
                " 같은 회복 약속도 금지다. 카드가 보장할 수 있는 영역이 아니다."
                " 진단명을 '성장통', '거쳐 가는 과정' 같은 말로 축소하지 마라."
                " 카드로는 지금의 마음 상태와 오늘 할 수 있는 돌봄까지만 말한다."
                " 그리고 리딩 안에 전문가(정신과·상담·병원) 도움을 함께 받으라는 말을"
                " 한 번 담아라. 겁주지 말고, 카드가 대신할 수 없는 영역이라는 톤으로"
                " 담담하게.")

    # 카드 시기값은 일이 움직이기 시작하는 속도지 실제 걸리는 기간이 아니다.
    # 구분하지 않으면 "언제 결혼할까?"에 컵2(2개월)를 붙여 "두 달 뒤 결혼"이 나간다.
    out += ("\n[시기 현실성] 위 시기감은 '흐름이 움직이기 시작하는 시점'이지 "
            "그 일이 완결되는 시점이 아니다. 결혼·취업·합격·이직처럼 "
            "절차와 시간이 필요한 사안은, 카드 시기를 '첫 신호가 오는 때'로 읽고 "
            "결말 시점은 그보다 넉넉하게 잡아라. "
            "예: 컵2가 2개월이면 '두 달 안에 인연이 보이기 시작하고, "
            "결혼까지는 그 뒤로 더 걸린다'가 맞는 해석이다.")
    return out
